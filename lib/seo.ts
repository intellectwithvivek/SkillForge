/**
 * Metadata and JSON-LD builders.
 *
 * Every route composes its metadata from `pageMetadata` so canonical URLs, Open Graph
 * and Twitter cards cannot be forgotten on a page-by-page basis.
 */

import type { Metadata } from 'next'
import { SITE, absolute } from './site'
import {
  averageRating,
  categoryName,
  contentMix,
  formatPrice,
  instructorFor,
  ratingsCount,
  totalHours,
  totalMinutes,
  type Course,
} from '@/data/courses'

interface PageMetaInput {
  title: string
  description: string
  /** Route path, e.g. `/courses`. Becomes the canonical URL. */
  path: string
  image?: string
  imageAlt?: string
  type?: 'website' | 'article'
}

export function pageMetadata({
  title,
  description,
  path,
  image,
  imageAlt,
  type = 'website',
}: PageMetaInput): Metadata {
  const url = absolute(path)

  /*
    The `images` key is spread in only when there is one, never set to
    `undefined`. Declaring `openGraph.images` at all — even as undefined —
    counts as the route taking ownership of its share image, which suppresses
    the one generated by `opengraph-image.tsx`. Omitting the key lets the file
    convention supply it: the site card for most routes, the per-course card on
    a course page.
  */
  const images = image ? [{ url: image, width: 1200, height: 630, alt: imageAlt ?? title }] : null

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type,
      url,
      title,
      description,
      siteName: SITE.name,
      locale: SITE.locale,
      ...(images ? { images } : {}),
    },
    twitter: {
      card: 'summary_large_image',
      title,
      description,
      ...(image ? { images: [image] } : {}),
    },
  }
}

